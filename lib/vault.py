def write_note(x: dict, body: str) -> str:
    """单文件预览笔记。frontmatter 用真实单值分类字段，便于 Obsidian 搜索 / Dataview 过滤。"""
    rel = note_rel(x)
    asset = x.get("asset") or asset_rel(x)
    status = "已下载" if x.get("downloaded") else "仅元数据 · 未下载"
    tags = [str(t) for t in (x.get("tags") or []) if t][:12]
    chain = _chain(x)  # source / group / domain / subject / kind
    fm = [
        "---",
        f'title: "{x["name"].replace(chr(34), chr(39))}"',
        f'source: "{x.get("source", "")}"', f'group: "{x.get("group", "")}"',
        f'domain: "{x.get("domain", "")}"', f'subject: "{x.get("subject", "")}"',
        f'kind: "{x.get("kind", "")}"', f'status: "{status}"',
        f'downloaded: {"true" if x.get("downloaded") else "false"}',
        'topics: [' + ", ".join(f'"{t.replace(chr(34), chr(39))}"' for t in tags) + ']',
        f'size: "{x.get("size", "")}"', f'source_path: "{x.get("path", "")}"',
        f'asset: "{asset}"', f'resource_id: "{x["id"]}"',
        f'tags: [资源管理, {safe(x.get("subject", "") or "综合")}, {safe(x.get("kind", "") or "其他资料")}]',
        "---", "",
        f"# {x['name']}", "",
        f"> 分类路径：{' › '.join(chain)}",
        f"> 来源：{x.get('source','')} / {x.get('group','')} ｜ 群内路径：`{x.get('path','')}` ｜ 体积：{x.get('size','')}",
        f"> 状态：{status} ｜ 上传者：{x.get('uploader','') or '未知'} ｜ 上传时间：{x.get('uploaded_at','') or '未知'}", "",
        "## 内容摘要", "", (x.get("summary") or "（尚未下载，无正文摘要；只有文件名、路径与分类等元数据）"), "",
        "## 原文件", "",
        (f"[打开原文件](<{'../' * 6}{asset}>)\n\n原文件路径：`{asset}`" if x.get("downloaded")
         else "原文件未下载，请在可视化界面中点「批量导入到 Obsidian」下载并自动分类入库。"),
        "", "## 正文全文（已抽取，供 Obsidian 搜索与 AI 读取）", "",
    ]
    text = "\n".join(fm)
    # v3.5.0：把**完整已抽取正文**写进笔记（上限可配），让 Obsidian 全局搜索、
    # Dataview、库内 AI 都能真正读到文件内容，而不是只有 3000 字片段。
    cap = int(config.CFG.get("note_body_chars", 20000))
    if body.strip():
        text += "```text\n" + body[:cap] + "\n```\n"
        if len(body) > cap:
            text += f"\n> 全文共 {len(body)} 字，笔记内收录前 {cap} 字；完整正文可由右侧 AI 面板「读取全文」获取。\n"
    else:
        text += "（无可提取正文，或尚未下载）\n"
    text += ("\n## 相关入口\n\n"
             "- [[00-资源总览]] · [[00-多级大纲]] · [[00-批量导入指南]] · [[00-AI检索说明]]\n"
             f"- 界面预览：`http://127.0.0.1:8787/?file={x['id']}`\n"
             "- AI 提问：右侧栏「资源 AI 搜索」（可问「四六级真题有哪些」）\n")
    _write(rel, text)
    return rel


def _wikilink(rel: str, label: str) -> str:
    return f"[[{Path(rel).stem}|{label}]]"


def recent_ids() -> set[str]:
    """最近一次/几次导入的条目 id，用于在大纲里给新导入文件打 🆕。"""
    d = config.read_json(config.state("import_recent.json"), {}) or {}
    return set(str(i) for i in (d.get("ids") or []))


def mark_recent(ids: list[str]) -> list[str]:
    old = list((config.read_json(config.state("import_recent.json"), {}) or {}).get("ids") or [])
    merged = [str(i) for i in ids] + [str(i) for i in old]
    seen, out = set(), []
    for i in merged:
        if i and i not in seen:
            seen.add(i)
            out.append(i)
    out = out[:60]
    config.write_json(config.state("import_recent.json"),
                      {"ids": out, "updated_at": datetime.now().isoformat(timespec="seconds")})
    return out


def _new_tag(x: dict, recent: set[str]) -> str:
    return " 🆕" if x["id"] in recent else ""


def build_outlines(cat: dict) -> dict:
    """生成总览 + 全量多级大纲 + 每个层级一页 MOC。"""
    xs = catalog.items(cat)
    c = catalog.counts(cat)
    recent = recent_ids()
    # v3.2.0：大纲按「领域 → 学科 → 类型」三级单值维度组织（不再使用已移除的 classify 多值维度）
    dims = ["domain", "subject", "kind"]
    groups: dict[tuple, list[dict]] = {}
    for x in xs:
        for depth in (1, 2, 3):
            groups.setdefault(tuple(str(x.get(dims[i], "")) for i in range(depth)), []).append(x)

    root = v()
    # 总览
    lines = ["# 资源管理 · 总览", "",
             f"授权可见条目 **{c['total']}** 份 ｜ 已下载 **{c['downloaded']}** 份 ｜ 仅元数据 **{c['metadata_only']}** 份",
             f"覆盖 **{c['subjects']}** 个学科、**{c['kinds']}** 种类型 ｜ 合计约 **{c['size_bytes']/1024/1024/1024:.2f} GB**", "",
             "## 按领域下钻", ""]
    for (dom,), items_ in sorted(((k, vv) for k, vv in groups.items() if len(k) == 1), key=lambda t: -len(t[1])):
        lines.append(f"- {_wikilink('大纲/' + safe(dom) + '.md', dom)} — {len(items_)} 份"
                     f"（已下载 {sum(1 for i in items_ if i.get('downloaded'))}）")
    lines += ["", "## 入口", "", "- [[00-本次导入]] 最近一次导入报告（🆕 标记的文件在这里）",
              "- [[00-多级大纲]] 全量逐级大纲", "- [[00-使用说明]] 使用说明", "",
              f"> 最近导入 {len(recent)} 份已在各级大纲中以 🆕 标出；"
              "未下载条目只有元数据，AI 不会推测其内容；需要内容请先在界面确认下载。"]
    _write("00-资源总览.md", "\n".join(lines) + "\n")

    # 全量大纲
    full = ["# 多级大纲", "", "> 领域 → 科目/主题 → 资源类型 → 单文件预览", ""]
    for (dom,), ditems in sorted(((k, vv) for k, vv in groups.items() if len(k) == 1), key=lambda t: -len(t[1])):
        full += [f"## {dom}（{len(ditems)}）", ""]
        for (d2, sub), sitems in sorted(((k, vv) for k, vv in groups.items() if len(k) == 2 and k[0] == dom),
                                        key=lambda t: -len(t[1])):
            full += [f"### {dom} > {sub}（{len(sitems)}）", ""]
            for (d3, s3, kind), kitems in sorted(
                    ((k, vv) for k, vv in groups.items() if len(k) == 3 and k[0] == dom and k[1] == sub),
                    key=lambda t: -len(t[1])):
                full.append(f"#### {kind}（{len(kitems)}）")
                full.append("")
                # 已下载（有笔记可点开）的条目优先列出，避免在 40 条截断时漏掉它们
                for x in sorted(kitems, key=lambda i: (not i.get("downloaded"), i["id"] not in recent, i["name"]))[:40]:
                    tag = _new_tag(x, recent)
                    if x.get("downloaded") and x.get("note"):
                        full.append(f"- {_wikilink(x['note'], x['name'])} ✅ 已下载{tag}")
                    else:
                        full.append(f"- {x['name']} · 仅元数据（未下载）{tag}")
                if len(kitems) > 40:
                    full.append(f"- … 其余 {len(kitems)-40} 份见界面")
                full.append("")
    _write("00-多级大纲.md", "\n".join(full) + "\n")

    # 每个节点一页
    pages = 0
    for key, gitems in groups.items():
        name = " / ".join(key)
        rel = "大纲/" + "__".join(safe(k) for k in key) + ".md"
        out = [f"# {name}", "", f"共 **{len(gitems)}** 份 ｜ 已下载 **{sum(1 for i in gitems if i.get('downloaded'))}** 份", "",
               "← [[00-资源总览]] ｜ [[00-多级大纲]]", ""]
        if len(key) < 3:
            out += ["## 下一级", ""]
            children = [(k, vv) for k, vv in groups.items()
                        if len(k) == len(key) + 1 and k[:len(key)] == key]
            for k, vv in sorted(children, key=lambda t: -len(t[1])):
                crel = "大纲/" + "__".join(safe(z) for z in k) + ".md"
                out.append(f"- {_wikilink(crel, k[-1])} — {len(vv)} 份")
            out.append("")
        out += ["## 单文件预览", ""]
        for x in sorted(gitems, key=lambda i: (not i.get("downloaded"), i["id"] not in recent, i["name"]))[:200]:
            tag = _new_tag(x, recent)
            if x.get("downloaded") and x.get("note"):
                out.append(f"- {_wikilink(x['note'], x['name'])} ✅ 已下载{tag}｜{x.get('size','')}")
            else:
                out.append(f"- {x['name']} · 仅元数据（未下载）{tag}｜{x.get('size','')}")
        _write(rel, "\n".join(out) + "\n")
        pages += 1
    return {"overview": "00-资源总览.md", "full": "00-多级大纲.md", "pages": pages,
            "notes": sum(1 for x in xs if x.get("downloaded"))}


def status(cat: dict | None = None) -> dict:
    """库状态：给主页「Obsidian 知识库」卡片与插件显示完整链路进度。"""
    cat = cat or catalog.load()
    xs = catalog.items(cat)
    root = v()
    dl = [x for x in xs if x.get("downloaded")]
    notes = sum(1 for x in dl if (root / x.get("note", "")).is_file()) if dl else 0
    assets = sum(1 for x in dl if (root / x.get("asset", "")).is_file()) if dl else 0
    outlines = len(list((root / "大纲").glob("*.md"))) if (root / "大纲").is_dir() else 0
    plugin = (root / ".obsidian" / "plugins" / "resource-manager-ai" / "main.js").is_file()
    by_kind: dict[str, int] = {}
    for x in dl:
        k = x.get("kind") or "其他资料"
        by_kind[k] = by_kind.get(k, 0) + 1
    return {
        "ok": True, "path": str(root), "name": root.name, "exists": root.is_dir(),
        "initialized": (root / "00-使用说明.md").is_file(),
        "total": len(xs), "downloaded": len(dl), "pending": len(xs) - len(dl),
        "notes": notes, "assets": assets, "outlines": outlines,
        "plugin": plugin, "by_kind": by_kind,
        "guides": ["00-使用说明.md", "00-批量导入指南.md", "00-AI检索说明.md",
                   "00-资源总览.md", "00-多级大纲.md", REPORT],
        "report": REPORT, "report_exists": (root / REPORT).is_file(),
        "recent": len(recent_ids()),
        "obsidian_auto_open": bool((config.CFG.get("obsidian") or {}).get("open_after_import", True)),
        "structure": "资源/来源/群聊/领域/学科/类型/原文件 · 笔记/同级路径/预览笔记.md · 大纲/多级 MOC",
    }


def search(q: str, cat: dict | None = None, group: str = "", limit: int = 20,
           scope: str = "vault") -> dict:
    """库内 AI 检索。

    scope='vault'：只搜已导入本库（有正文/笔记）的条目，结果可直接点开笔记（旧行为）。
    scope='all'  ：覆盖**全部目录资料**；已导入的可读取完整正文，未下载的明确标注仅元数据。
    两种范围都用 vocab 自适应词典做泛化扩展，任意学科都能召回。
    """
    cat = cat or catalog.load()
    root = v()
    q = (q or "").strip()
    if not q:
        return {"ok": True, "query": q, "found": False, "items": [], "total": 0,
                "scope": scope, "answer": "请输入检索词。"}
    xs = catalog.items(cat)
    if group:
        xs = [x for x in xs if str(x.get("group", "")) == group]
    pool = ([x for x in xs if x.get("downloaded") and (root / x.get("note", "")).is_file()]
            if scope == "vault" else list(xs))
    if not pool:
        return {"ok": True, "query": q, "found": False, "items": [], "total": 0,
                "scanned": len(xs), "scope": scope,
                "answer": ("本库还没有已导入的资料。请先在界面里批量导入，再使用库内检索。"
                           if scope == "vault" else "目录为空。")}
    ids = {x["id"] for x in pool}
    try:
        extra = sorted(set(vocab.get(cat).expand(q)[1]) | set(vocab.get(cat).cut(q)))
    except Exception:
        extra = []
    try:
        hits = [h for h in index.search(q, max(60, limit * 4), extra=extra) if h["item_id"] in ids]
    except TypeError:
        hits = [h for h in index.search(q, max(60, limit * 4)) if h["item_id"] in ids]
    # FTS 没命中时退回到「词面命中」，保证文件名 / 分类标签也能被搜到
    if not hits:
        terms = [t.lower() for t in index.query_terms(q) if len(t) >= 2] + [e.lower() for e in extra]
        scored = []
        for x in pool:
            hay = (" ".join(str(x.get(k, "") or "") for k in
                            ("name", "path", "folder", "domain", "subject", "kind", "summary", "group"))
                   + " " + " ".join(str(t) for t in (x.get("tags") or []))).lower()
            score = sum(1 for t in terms if t in hay)
            if score:
                scored.append((score, x))
        scored.sort(key=lambda t: -t[0])
        hits = [{"item_id": x["id"], "body": "", "title": x.get("name", "")}
                for _, x in scored[:max(60, limit * 4)]]
    by_id = {x["id"]: x for x in pool}
    items, seen = [], set()
    for h in hits:
        x = by_id.get(h["item_id"])
        if not x or x["id"] in seen:
            continue
        seen.add(x["id"])
        body = h.get("body", "") or ""
        if not body.strip() and x.get("downloaded"):
            bp = index.body_path(x["id"])
            if bp.is_file():
                body = bp.read_text(encoding="utf-8", errors="replace")[:60000]
        excerpt = re.sub(r"\s+", " ", body).strip()[:600]
        items.append({
            "id": x["id"], "name": x.get("name", ""), "note": x.get("note", ""),
            "asset": x.get("asset", ""), "group": x.get("group", ""),
            "domain": x.get("domain", ""), "subject": x.get("subject", ""),
            "kind": x.get("kind", ""), "summary": x.get("summary", ""),
            "downloaded": bool(x.get("downloaded")), "has_body": bool(body.strip()),
            "body_chars": len(body), "excerpt": excerpt,
            "chain": " › ".join(_chain(x)),
            "wikilink": ("[[" + Path(x["note"]).stem + "|" + x.get("name", "") + "]]"
                         if x.get("downloaded") and x.get("note") else ""),
        })
        if len(items) >= limit:
            break
    head = (f"库内已导入 {len(pool)} 份资料，命中 {len(items)} 份（按相关度）。"
            if scope == "vault" else
            f"已检索全部 {len(pool)} 份资料，命中 {len(items)} 份；"
            f"其中 {sum(1 for i in items if i['has_body'])} 份含完整正文，可直接读取全文。")
    return {"ok": True, "query": q, "found": bool(items), "items": items,
            "total": len(pool), "scanned": len(xs), "matched": len(items),
            "scope": scope, "path": str(root),
            "answer": head + "点开源文件索引即可在 Obsidian 内打开笔记或读取全文。"}


def content(item_id: str, cat: dict | None = None) -> dict:
    """读取某份资料的**完整已抽取正文**（仅已导入条目）。供库内 AI「读取全文」。"""
    cat = cat or catalog.load()
    x = catalog.by_id(cat, str(item_id or ""))
    if not x:
        return {"ok": False, "error": "目录中没有该资料"}
    base = {"ok": True, "id": x["id"], "name": x.get("name", ""),
            "downloaded": bool(x.get("downloaded")), "note": x.get("note", ""),
            "asset": x.get("asset", ""), "chain": " › ".join(_chain(x)),
            "subject": x.get("subject", ""), "kind": x.get("kind", "")}
    if not x.get("downloaded"):
        return {**base, "body": "", "body_chars": 0,
                "note_text": "仅元数据，未下载，无正文；请先在界面批量导入。"}
    bp = index.body_path(x["id"])
    try:
        body = bp.read_text(encoding="utf-8", errors="replace") if bp.is_file() else ""
    except OSError:
        body = ""
    return {**base, "body": body, "body_chars": len(body),
            "note_text": "已读取全文，可交给 AI 概括或作为上下文。"}


def refresh_notes(cat: dict | None = None) -> int:
    """用当前模板重生成**全部**已导入笔记，保证每份都写入完整正文（升级后旧笔记也补齐）。"""
    cat = cat or catalog.load()
    n = 0
    for x in catalog.items(cat):
        if not x.get("downloaded"):
            continue
        bp = index.body_path(x["id"])
        body = ""
        if bp.is_file():
            try:
                body = bp.read_text(encoding="utf-8", errors="replace")
            except OSError:
                body = ""
        x["note"] = write_note(x, body)
        n += 1
    if n:
        catalog.save(cat)
        index.sync(cat)
    return n


def discover_vaults() -> list[dict]:
    """列出本机能挑的 Obsidian 库：官方注册表 + 常见位置浅扫 + 当前库。"""
    out: list[dict] = []
    seen: set[str] = set()

    def add(p) -> None:
        try:
            p = Path(p).resolve()
            key = str(p).lower()
            if not p.is_dir() or key in seen:
                return
            seen.add(key)
            out.append({"name": p.name, "path": str(p),
                        "obsidian": (p / ".obsidian").is_dir(),
                        "plugin": (p / ".obsidian" / "plugins" / "resource-manager-ai" / "main.js").is_file(),
                        "current": p == v().resolve()})
        except (OSError, ValueError):
            return

    add(v())
    appdata = os.environ.get("APPDATA") or ""
    if appdata:
        reg = Path(appdata) / "obsidian" / "obsidian.json"
        data = config.read_json(reg, {}) or {}
        if not isinstance(data, dict):
            data = {}
        for item in (data.get("vaults") or {}).values():
            if isinstance(item, dict):
                add(item.get("path", ""))
            elif isinstance(item, str):
                add(item)
    for base in (Path.home() / "Desktop", Path.home() / "Documents", Path.home()):
        if not base.is_dir():
            continue
        try:
            for child in list(base.iterdir())[:180]:
                if child.is_dir() and (child / ".obsidian").is_dir():
                    add(child)
        except OSError:
            continue
    return out[:40]


def set_vault(target: dict) -> dict:
    """挑选目标库：current / existing（必须是本机已发现的库）/ new（桌面新建）。

    切到已有库时**保留其原有 .obsidian 配置**，只追加 AI 插件与本工具生成的笔记。
    并把已导入的原文件与笔记迁移到新库，保证「已导入的内容」不丢。
    """
    kind = str((target or {}).get("kind") or "current").strip()
    old = v()
    if kind == "new":
        name = safe(str((target or {}).get("name") or "")).strip()
        if not name or name in ("unnamed", "."):
            return {"ok": False, "error": "请填写有效的库名称"}
        base = Path.home() / "Desktop"
        raw_base = str((target or {}).get("base") or "").strip()
        if raw_base:
            try:
                cand = Path(raw_base).resolve()
                home = Path.home().resolve()
                if cand == home or home in cand.parents:
                    base = cand  # 只允许建在用户目录内，避免任意路径写入
            except (OSError, ValueError):
                pass
        path = base / name
    elif kind == "existing":
        raw = str((target or {}).get("path") or "")
        known = {d["path"]: d for d in discover_vaults()}
        hit = next((p for p in known if str(Path(p).resolve()).lower() == str(Path(raw).resolve()).lower()), None) \
            if raw else None
        if not hit:
            return {"ok": False, "error": "该库不在本机已发现的 Obsidian 库列表中"}
        path = Path(hit)
    else:
        path = old
    cat = catalog.load()
    if path.resolve() != old.resolve():
        config.CFG["vault"] = str(path)
        config.write_json(config.CONFIG_PATH, config.CFG)
    init()
    migrated = 0
    for x in catalog.items(cat):
        if not x.get("downloaded"):
            continue
        rel = asset_rel(x)
        src = old / (x.get("asset") or rel)
        dst = path / rel
        if not dst.is_file() and src.is_file():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        bp = index.body_path(x["id"])
        body = ""
        if bp.is_file():
            try:
                body = bp.read_text(encoding="utf-8", errors="replace")
            except OSError:
                body = ""
        x["asset"] = rel
        x["note"] = write_note(x, body)
        migrated += 1
    if migrated:
        catalog.save(cat)
        index.sync(cat)
    return {"ok": True, "path": str(path), "name": path.name, "migrated": migrated,
            "outlines": build_outlines(cat), "vault": status(cat)}


def open_in_obsidian(file_rel: str = "") -> dict:
    """导入后自动拉起 Obsidian 并定位到指定笔记；协议未注册时回退打开库文件夹。"""
    root = v()
    rel = str(file_rel or (config.CFG.get("obsidian") or {}).get("open_file") or REPORT)
    rel = rel.replace("\\", "/")
    if rel.lower().endswith(".md"):
        rel = rel[:-3]
    uri = "obsidian://open?" + urllib.parse.urlencode({"vault": root.name, "file": rel})
    import sys
    try:
        if sys.platform.startswith("win"):
            os.startfile(uri)  # noqa: S606 - 仅本机、用户显式触发
        else:
            import webbrowser
            webbrowser.open(uri)
        return {"ok": True, "opened": True, "method": "obsidian_uri",
                "uri": uri, "path": str(root), "file": rel}
    except Exception as e:
        err = f"{type(e).__name__}: {str(e)[:120]}"
    try:
        if sys.platform.startswith("win"):
            os.startfile(str(root))  # noqa: S606
        else:
            import webbrowser
            webbrowser.open(root.as_uri())
        return {"ok": True, "opened": True, "method": "folder", "uri": uri,
                "path": str(root), "file": rel, "error": err,
                "note": "Obsidian 协议未注册，已打开库文件夹；请在 Obsidian 里「打开文件夹作为库」"}
    except Exception as e2:
        return {"ok": True, "opened": False, "method": "none", "uri": uri,
                "path": str(root), "file": rel, "error": err + " / " + str(e2)[:120]}


def write_import_report(cat: dict, results: list[dict], meta: dict | None = None) -> str:
    """导入成效报告：新文件落在哪些**原有分类**里、生成了什么、AI 现在能读到什么。"""
    meta = meta or {}
    ok = [r for r in (results or []) if r.get("ok")]
    idx = {x["id"]: x for x in catalog.items(cat)}
    by_chain: dict[tuple, list[dict]] = {}
    for r in ok:
        x = idx.get(str(r.get("id", "")))
        if x:
            by_chain.setdefault((x.get("domain", ""), x.get("subject", ""), x.get("kind", "")), []).append(x)
    total_dl = sum(1 for x in catalog.items(cat) if x.get("downloaded"))
    lines = [
        "# 本次导入 · 成效报告", "",
        f"> 时间：{datetime.now().strftime('%Y-%m-%d %H:%M:%S')} ｜ 通道：{esc_md(str(meta.get('source') or 'QQ 群文件'))}"
        f" ｜ 成功 **{len(ok)}/{len(results or [])}** ｜ 本库已导入 **{total_dl}/{len(catalog.items(cat))}** 份", "",
        "## 立刻能看到什么", "",
        "- 原文件已按 `资源/来源/群聊/领域/学科/类型/` 自动分类落盘；"
        "每份都有同名预览笔记，正文全文已写入笔记，Obsidian 全局搜索可直接搜到内容。",
        "- 各级大纲已刷新，本次新增文件带 **🆕** 标记，位置就在原有分类里，不需要手工整理。",
        "- AI 插件已自动部署；右侧「资源 AI 搜索」可检索**全部资料**，已导入的能读取完整正文。",
        "- 这份报告就是导入完成后程序自动打开的第一页。", "",
        "## 新文件落在原有分类的哪里", "",
    ]
    if not by_chain:
        lines.append("（本次没有成功导入新文件）")
    for key, xs in sorted(by_chain.items(), key=lambda t: (-len(t[1]), " › ".join(t[0]))):
        rel = "大纲/" + "__".join(safe(k) for k in key) + ".md"
        lines += [f"### {' › '.join(key)}（新增 {len(xs)} 份）", "",
                  f"分类入口：{_wikilink(rel, '打开这一类的原有大纲')}", ""]
        for x in xs:
            bp = index.body_path(x["id"])
            chars = 0
            if bp.is_file():
                try:
                    chars = len(bp.read_text(encoding="utf-8", errors="replace"))
                except OSError:
                    chars = 0
            link = _wikilink(x["note"], x["name"]) if x.get("note") else x["name"]
            lines.append(f"- {link} ✅ 已下载 🆕 ｜ 正文 {chars} 字 ｜ {x.get('size', '')}")
        lines.append("")
    lines += [
        "## 在 Obsidian 里继续", "",
        "- 右侧栏「资源 AI 搜索」：范围选「全部资料」可覆盖整目录；点「读取全文」可查看已导入文件正文。",
        "- [[00-多级大纲]] 查看 🆕 文件在全部分类里的位置；[[00-资源总览]] 看统计。",
        "- [[00-AI检索说明]] ／ [[00-批量导入指南]] ／ [[00-使用说明]]", "",
        "> 未下载条目只有元数据，AI 不会推测其内容；需要内容请在界面里继续批量导入。",
    ]
    _write(REPORT, "\n".join(lines) + "\n")
    return REPORT


def esc_md(s: str) -> str:
    """报告文本里避免竖线破坏 Markdown 表格/引用。"""
    return str(s).replace("|", "\\|").replace("\n", " ")

def write_note(x: dict, body: str) -> str:
    """单文件预览笔记。frontmatter 用真实单值分类字段，便于 Obsidian 搜索 / Dataview 过滤。"""
    rel = note_rel(x)
    asset = x.get("asset") or asset_rel(x)
    status = "已下载" if x.get("downloaded") else "仅元数据 · 未下载"
    tags = [str(t) for t in (x.get("tags") or []) if t][:12]
    chain = _chain(x)  # source / group / domain / subject / kind
    fm = [
        "---",
        f'title: "{x["name"].replace(chr(34), chr(39))}"',
        f'source: "{x.get("source", "")}"', f'group: "{x.get("group", "")}"',
        f'domain: "{x.get("domain", "")}"', f'subject: "{x.get("subject", "")}"',
        f'kind: "{x.get("kind", "")}"', f'status: "{status}"',
        f'downloaded: {"true" if x.get("downloaded") else "false"}',
        'topics: [' + ", ".join(f'"{t.replace(chr(34), chr(39))}"' for t in tags) + ']',
        f'size: "{x.get("size", "")}"', f'source_path: "{x.get("path", "")}"',
        f'asset: "{asset}"', f'resource_id: "{x["id"]}"',
        f'tags: [资源管理, {safe(x.get("subject", "") or "综合")}, {safe(x.get("kind", "") or "其他资料")}]',
        "---", "",
        f"# {x['name']}", "",
        f"> 分类路径：{' › '.join(chain)}",
        f"> 来源：{x.get('source','')} / {x.get('group','')} ｜ 群内路径：`{x.get('path','')}` ｜ 体积：{x.get('size','')}",
        f"> 状态：{status} ｜ 上传者：{x.get('uploader','') or '未知'} ｜ 上传时间：{x.get('uploaded_at','') or '未知'}", "",
        "## 内容摘要", "", (x.get("summary") or "（尚未下载，无正文摘要；只有文件名、路径与分类等元数据）"), "",
        "## 原文件", "",
        (f"[打开原文件](<{'../' * 6}{asset}>)\n\n原文件路径：`{asset}`" if x.get("downloaded")
         else "原文件未下载，请在可视化界面中点「批量导入到 Obsidian」下载并自动分类入库。"),
        "", "## 正文片段", "",
    ]
    text = "\n".join(fm)
    if body.strip():
        text += "```text\n" + body[:3000] + "\n```\n"
    else:
        text += "（无可提取正文，或尚未下载）\n"
    text += ("\n## 相关入口\n\n"
             "- [[00-资源总览]] · [[00-多级大纲]] · [[00-批量导入指南]] · [[00-AI检索说明]]\n"
             f"- 界面预览：`http://127.0.0.1:8787/?file={x['id']}`\n"
             "- AI 提问：右侧栏「资源 AI 搜索」（可问「四六级真题有哪些」）\n")
    _write(rel, text)
    return rel


def _wikilink(rel: str, label: str) -> str:
    return f"[[{Path(rel).stem}|{label}]]"


def build_outlines(cat: dict) -> dict:
    """生成总览 + 全量多级大纲 + 每个层级一页 MOC。"""
    xs = catalog.items(cat)
    c = catalog.counts(cat)
    # v3.2.0：大纲按「领域 → 学科 → 类型」三级单值维度组织（不再使用已移除的 classify 多值维度）
    dims = ["domain", "subject", "kind"]
    groups: dict[tuple, list[dict]] = {}
    for x in xs:
        for depth in (1, 2, 3):
            groups.setdefault(tuple(str(x.get(dims[i], "")) for i in range(depth)), []).append(x)

    root = v()
    # 总览
    lines = ["# 资源管理 · 总览", "",
             f"授权可见条目 **{c['total']}** 份 ｜ 已下载 **{c['downloaded']}** 份 ｜ 仅元数据 **{c['metadata_only']}** 份",
             f"覆盖 **{c['subjects']}** 个学科、**{c['kinds']}** 种类型 ｜ 合计约 **{c['size_bytes']/1024/1024/1024:.2f} GB**", "",
             "## 按领域下钻", ""]
    for (dom,), items_ in sorted(((k, vv) for k, vv in groups.items() if len(k) == 1), key=lambda t: -len(t[1])):
        lines.append(f"- {_wikilink('大纲/' + safe(dom) + '.md', dom)} — {len(items_)} 份"
                     f"（已下载 {sum(1 for i in items_ if i.get('downloaded'))}）")
    lines += ["", "## 入口", "", "- [[00-多级大纲]] 全量逐级大纲", "- [[00-使用说明]] 使用说明", "",
              "> 未下载条目只有元数据，AI 不会推测其内容；需要内容请先在界面确认下载。"]
    _write("00-资源总览.md", "\n".join(lines) + "\n")

    # 全量大纲
    full = ["# 多级大纲", "", "> 领域 → 科目/主题 → 资源类型 → 单文件预览", ""]
    for (dom,), ditems in sorted(((k, vv) for k, vv in groups.items() if len(k) == 1), key=lambda t: -len(t[1])):
        full += [f"## {dom}（{len(ditems)}）", ""]
        for (d2, sub), sitems in sorted(((k, vv) for k, vv in groups.items() if len(k) == 2 and k[0] == dom),
                                        key=lambda t: -len(t[1])):
            full += [f"### {dom} > {sub}（{len(sitems)}）", ""]
            for (d3, s3, kind), kitems in sorted(
                    ((k, vv) for k, vv in groups.items() if len(k) == 3 and k[0] == dom and k[1] == sub),
                    key=lambda t: -len(t[1])):
                full.append(f"#### {kind}（{len(kitems)}）")
                full.append("")
                # 已下载（有笔记可点开）的条目优先列出，避免在 40 条截断时漏掉它们
                for x in sorted(kitems, key=lambda i: (not i.get("downloaded"), i["name"]))[:40]:
                    if x.get("downloaded") and x.get("note"):
                        full.append(f"- {_wikilink(x['note'], x['name'])} ✅ 已下载")
                    else:
                        full.append(f"- {x['name']} · 仅元数据（未下载）")
                if len(kitems) > 40:
                    full.append(f"- … 其余 {len(kitems)-40} 份见界面")
                full.append("")
    _write("00-多级大纲.md", "\n".join(full) + "\n")

    # 每个节点一页
    pages = 0
    for key, gitems in groups.items():
        name = " / ".join(key)
        rel = "大纲/" + "__".join(safe(k) for k in key) + ".md"
        out = [f"# {name}", "", f"共 **{len(gitems)}** 份 ｜ 已下载 **{sum(1 for i in gitems if i.get('downloaded'))}** 份", "",
               "← [[00-资源总览]] ｜ [[00-多级大纲]]", ""]
        if len(key) < 3:
            out += ["## 下一级", ""]
            children = [(k, vv) for k, vv in groups.items()
                        if len(k) == len(key) + 1 and k[:len(key)] == key]
            for k, vv in sorted(children, key=lambda t: -len(t[1])):
                crel = "大纲/" + "__".join(safe(z) for z in k) + ".md"
                out.append(f"- {_wikilink(crel, k[-1])} — {len(vv)} 份")
            out.append("")
        out += ["## 单文件预览", ""]
        for x in sorted(gitems, key=lambda i: (not i.get("downloaded"), i["name"]))[:200]:
            if x.get("downloaded") and x.get("note"):
                out.append(f"- {_wikilink(x['note'], x['name'])} ✅ 已下载｜{x.get('size','')}")
            else:
                out.append(f"- {x['name']} · 仅元数据（未下载）｜{x.get('size','')}")
        _write(rel, "\n".join(out) + "\n")
        pages += 1
    return {"overview": "00-资源总览.md", "full": "00-多级大纲.md", "pages": pages,
            "notes": sum(1 for x in xs if x.get("downloaded"))}


def status(cat: dict | None = None) -> dict:
    """库状态：给主页「Obsidian 知识库」卡片与插件显示完整链路进度。"""
    cat = cat or catalog.load()
    xs = catalog.items(cat)
    root = v()
    dl = [x for x in xs if x.get("downloaded")]
    notes = sum(1 for x in dl if (root / x.get("note", "")).is_file()) if dl else 0
    assets = sum(1 for x in dl if (root / x.get("asset", "")).is_file()) if dl else 0
    outlines = len(list((root / "大纲").glob("*.md"))) if (root / "大纲").is_dir() else 0
    plugin = (root / ".obsidian" / "plugins" / "resource-manager-ai" / "main.js").is_file()
    by_kind: dict[str, int] = {}
    for x in dl:
        k = x.get("kind") or "其他资料"
        by_kind[k] = by_kind.get(k, 0) + 1
    return {
        "ok": True, "path": str(root), "name": root.name, "exists": root.is_dir(),
        "initialized": (root / "00-使用说明.md").is_file(),
        "total": len(xs), "downloaded": len(dl), "pending": len(xs) - len(dl),
        "notes": notes, "assets": assets, "outlines": outlines,
        "plugin": plugin, "by_kind": by_kind,
        "guides": ["00-使用说明.md", "00-批量导入指南.md", "00-AI检索说明.md",
                   "00-资源总览.md", "00-多级大纲.md"],
        "structure": "资源/来源/群聊/领域/学科/类型/原文件 · 笔记/同级路径/预览笔记.md · 大纲/多级 MOC",
    }


def search(q: str, cat: dict | None = None, group: str = "", limit: int = 20) -> dict:
    """库内 AI 检索：只在**已导入本库（有正文/笔记）**的条目里找，结果可直接点开笔记。

    与 /api/ask 的区别：这里保证每条结果都有本地笔记与正文片段，
    专供 Obsidian 插件「库内检索」使用，不会返回未下载的元数据条目。
    """
    cat = cat or catalog.load()
    root = v()
    q = (q or "").strip()
    if not q:
        return {"ok": True, "query": q, "found": False, "items": [], "total": 0,
                "answer": "请输入检索词。"}
    dl = [x for x in catalog.items(cat)
          if x.get("downloaded") and (root / x.get("note", "")).is_file()]
    if group:
        dl = [x for x in dl if str(x.get("group", "")) == group]
    if not dl:
        return {"ok": True, "query": q, "found": False, "items": [], "total": 0,
                "answer": "本库还没有已导入的资料。请先在界面里批量导入，再使用库内检索。"}
    ids = {x["id"] for x in dl}
    hits = [h for h in index.search(q, max(40, limit * 3)) if h["item_id"] in ids]
    terms = [t.lower() for t in index.query_terms(q) if len(t) >= 2]
    # FTS 没命中时退回到「词面命中」，保证库内文件名 / 分类标签也能被搜到
    if not hits:
        scored = []
        for x in dl:
            hay = " ".join(str(x.get(k, "") or "") for k in
                           ("name", "path", "folder", "domain", "subject", "kind", "summary")) + \
                  " " + " ".join(str(t) for t in (x.get("tags") or []))
            hay = hay.lower()
            score = sum(1 for t in terms if t in hay)
            if score:
                scored.append((score, x, ""))
        scored.sort(key=lambda t: -t[0])
        hits = [{"item_id": x["id"], "body": "", "title": x.get("name", "")}
                for _, x, _ in scored[:max(40, limit * 3)]]
    by_id = {x["id"]: x for x in dl}
    items, seen = [], set()
    for h in hits:
        x = by_id.get(h["item_id"])
        if not x or x["id"] in seen:
            continue
        seen.add(x["id"])
        body = h.get("body", "") or ""
        if not body.strip():
            bp = index.body_path(x["id"])
            if bp.is_file():
                body = bp.read_text(encoding="utf-8", errors="replace")[:60000]
        excerpt = re.sub(r"\s+", " ", body).strip()[:260]
        items.append({
            "id": x["id"], "name": x.get("name", ""), "note": x.get("note", ""),
            "asset": x.get("asset", ""), "group": x.get("group", ""),
            "domain": x.get("domain", ""), "subject": x.get("subject", ""),
            "kind": x.get("kind", ""), "summary": x.get("summary", ""),
            "excerpt": excerpt, "chain": " › ".join(_chain(x)),
            "wikilink": "[[" + Path(x["note"]).stem + "|" + x.get("name", "") + "]]",
        })
        if len(items) >= limit:
            break
    return {"ok": True, "query": q, "found": bool(items), "items": items,
            "total": len(dl), "matched": len(items), "path": str(root),
            "answer": f"库内已导入 {len(dl)} 份资料，命中 {len(items)} 份（按相关度）。"
                      "点开右侧源文件索引即可在 Obsidian 内打开笔记。"}

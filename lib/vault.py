"""独立 Obsidian 库：多级大纲 MOC、单文件预览笔记、插件部署、库内检索。

所有脚本生成的内容都带 NOTE_MARK，重建时只删带标记的笔记，不碰手工笔记。
v3.4.0：补齐「批量导入 → 自动分类入库 → 库内 AI 检索」的完整链路，
        笔记 frontmatter 改用真实的单值分类字段（旧 genre/modality 占位已废弃）。
"""
from __future__ import annotations

import re
import shutil
from pathlib import Path

from . import catalog, config, index, qq

NOTE_MARK = "<!-- generated by resource-manager -->"


def v() -> Path:
    return config.vault()


def safe(name: str) -> str:
    return re.sub(r'[\\/:*?"<>|#\[\]^]', "_", (name or "unnamed")).strip()[:120] or "unnamed"


def _chain(x: dict) -> list[str]:
    return [safe(x.get(k, "")) for k in ("source", "group", "domain", "subject", "kind")]


def asset_rel(x: dict) -> str:
    stem, ext = Path(x["name"]).stem, Path(x["name"]).suffix
    tail = f"{safe(stem)}-{x['id'][3:9]}{ext}"
    return "/".join(["资源", *_chain(x), tail])


def note_rel(x: dict) -> str:
    return "/".join(["笔记", *_chain(x), safe(Path(x["name"]).stem) + "-" + x["id"][3:9] + ".md"])


def _write(rel: str, text: str) -> Path:
    p = v() / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(NOTE_MARK + "\n" + text, encoding="utf-8")
    return p


